// # 調査結果
console.log("𠮷野家"[0]); // => �
console.log("👨‍👨‍👧‍👧"[0]); // => �

// # 説明
console.log("𠮷".length); // 2
console.log("𠮷".charCodeAt(0)); // 55362 =  0xD842
// より、"𠮷"はサロゲートペア（2つの16ビット値の並び）として表現される。
// "𠮷野家"[0]は、"𠮷"の前半の16ビット値"\uD842"を示し、単独で文字として成立しないため、�と表示された。

// "👨‍👨‍👧‍👧"は、"👨 + ZWJ（ゼロ幅接合子） + 👨 + ZWJ + 👧 + ZWJ + 👧"として表現される。
console.log("👨‍👨‍👧‍👧".length); // 11 = 4絵文字(length 8) + 3zwj(length 3)
// 先頭の"👨"も
console.log("👨".length); // 2
console.log("👨".charCodeAt(0)); // 55357 = 0xD83D
// よりサロゲートペアとなり、"👨‍👨‍👧‍👧"[0]は"👨"の前半の"\uD83D"となるが、これも単独で文字として成立しないため、�と表示された。

// # 問題7.8で得た知見
// 絵文字はゼロ幅接合子を使用することで、組み合わせることが可能。
// 人間が認識するような一文字単位(書記素単位)で扱いたい場合は、Intl.Segmenterを利用する方がよい。
// 参考書の5.4.4.2 では文字列に対してfor/of文を使用すれば、サロゲートペアも1文字として扱え、文字数分のループが扱えそうだが
// 以下のような場合は、7ループ（👨, ZWJ, 👨, ZWJ, 👧, ZWJ, 👧）回るため注意が必要だと感じた。
for (const letter of "👨‍👨‍👧‍👧") {
  console.log(letter);
}
